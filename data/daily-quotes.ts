/**
 * Returns the deterministic quote for today (or a specific date).
 * Ensures:
 * 1. Every single calendar day of the year gets its own unique quote (Day 1 to Day 366).
 * 2. Multi-year progression: Year 1 (2025/2026), Year 2 (2027), Year 3 (2028) each
 *    receive distinct quotes across the calendar cycle via a prime salt offset.
 * 3. 100% offline reliable with zero network latency or external API failure risk.
 */
export function getDailyQuoteForDate(date: Date = new Date()): DailyLegalQuote {
  const now = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = now.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.max(1, Math.floor(diff / oneDay)); // 1 to 366

  // Multi-year offset: In year 2026 offset is 181, in 2027 offset is 362, in 2025 offset is 0
  const yearOffset = (date.getFullYear() - 2025) * 181;
  const total = DAILY_LEGAL_QUOTES.length;
  const index = Math.abs((dayOfYear - 1 + yearOffset) % total);

  return DAILY_LEGAL_QUOTES[index];
}
